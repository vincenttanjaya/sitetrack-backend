CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 150),
    email text NOT NULL UNIQUE CHECK (email = lower(email) AND length(email) <= 254),
    password_hash text NOT NULL,
    role text NOT NULL CHECK (role IN ('user', 'company_store_manager', 'superadmin')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sessions (
    id text PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    refresh_hash bytea NOT NULL UNIQUE CHECK (octet_length(refresh_hash) = 32),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz
);
CREATE INDEX sessions_expiry_idx ON sessions (expires_at);

CREATE TABLE projects (
    number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK (number > 0),
    id text GENERATED ALWAYS AS ('PRJ-' || lpad(number::text, greatest(4, length(number::text)), '0')) STORED PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    start_date date NOT NULL,
    end_date date NOT NULL CHECK (end_date >= start_date),
    next_task_number bigint NOT NULL DEFAULT 1 CHECK (next_task_number > 0)
);
CREATE INDEX projects_name_idx ON projects (lower(name), number);
CREATE INDEX projects_start_date_idx ON projects (start_date, number);

CREATE TABLE project_members (
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES users(id),
    is_admin boolean NOT NULL DEFAULT false,
    joined_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, user_id)
);
CREATE INDEX project_members_user_idx ON project_members (user_id, project_id);

CREATE TABLE invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    recipient_id bigint NOT NULL REFERENCES users(id),
    sender_id bigint NOT NULL REFERENCES users(id),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected', 'withdrawn')),
    created_at timestamptz NOT NULL DEFAULT now(),
    read_at timestamptz,
    responded_at timestamptz,
    CHECK ((status = 'pending') = (responded_at IS NULL)),
    CHECK (recipient_id <> sender_id)
);
CREATE UNIQUE INDEX invitations_pending_idx ON invitations (project_id, recipient_id) WHERE status = 'pending';
CREATE INDEX invitations_project_pending_idx ON invitations (project_id, created_at DESC, id DESC) WHERE status = 'pending';
CREATE INDEX invitations_recipient_idx ON invitations (recipient_id, created_at DESC, id DESC);
CREATE INDEX invitations_unread_idx ON invitations (recipient_id) WHERE read_at IS NULL AND status <> 'withdrawn';

CREATE TABLE tasks (
    project_id text NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    number bigint NOT NULL CHECK (number > 0),
    id text GENERATED ALWAYS AS (project_id || '-T-' || lpad(number::text, greatest(4, length(number::text)), '0')) STORED UNIQUE,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    start_date date NOT NULL,
    end_date date NOT NULL CHECK (end_date >= start_date),
    status text NOT NULL DEFAULT 'not_started' CHECK (status IN ('not_started', 'in_progress', 'done')),
    PRIMARY KEY (project_id, number)
);
CREATE INDEX tasks_project_status_idx ON tasks (project_id, status);
CREATE INDEX tasks_project_name_idx ON tasks (project_id, lower(name), number);
CREATE INDEX tasks_project_start_idx ON tasks (project_id, start_date, number);
CREATE INDEX tasks_project_end_idx ON tasks (project_id, end_date, number);

CREATE TABLE task_dependencies (
    project_id text NOT NULL,
    task_number bigint NOT NULL,
    prerequisite_number bigint NOT NULL,
    PRIMARY KEY (project_id, task_number, prerequisite_number),
    FOREIGN KEY (project_id, task_number) REFERENCES tasks(project_id, number) ON DELETE CASCADE,
    FOREIGN KEY (project_id, prerequisite_number) REFERENCES tasks(project_id, number) ON DELETE CASCADE,
    CHECK (task_number <> prerequisite_number)
);
CREATE INDEX task_dependencies_reverse_idx ON task_dependencies (project_id, prerequisite_number, task_number);

CREATE TABLE stores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id text UNIQUE REFERENCES projects(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX company_store_singleton_idx ON stores ((project_id IS NULL)) WHERE project_id IS NULL;
INSERT INTO stores (project_id) VALUES (NULL);

CREATE TABLE materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    category text NOT NULL CHECK (length(category) BETWEEN 1 AND 120),
    unit text NOT NULL CHECK (length(unit) BETWEEN 1 AND 50)
);
CREATE INDEX materials_name_idx ON materials (lower(name), id);
CREATE INDEX materials_category_idx ON materials (lower(category), id);

CREATE TABLE stock (
    store_id bigint NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    material_id bigint NOT NULL REFERENCES materials(id),
    quantity bigint NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reorder_point bigint NOT NULL DEFAULT 0 CHECK (reorder_point >= 0),
    last_delivery_at timestamptz,
    PRIMARY KEY (store_id, material_id)
);
CREATE INDEX stock_material_idx ON stock (material_id, store_id);
CREATE INDEX stock_quantity_idx ON stock (store_id, quantity, material_id);
CREATE INDEX stock_last_delivery_idx ON stock (store_id, last_delivery_at, material_id);

CREATE TABLE deliveries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id text NOT NULL REFERENCES projects(id),
    direction text NOT NULL CHECK (direction IN ('company_to_project', 'project_to_company')),
    status text NOT NULL DEFAULT 'in_transit' CHECK (status IN ('in_transit', 'delivered', 'rejected', 'cancelled')),
    sent_at timestamptz NOT NULL DEFAULT now(),
    sent_by bigint NOT NULL REFERENCES users(id),
    resolved_at timestamptz,
    resolved_by bigint REFERENCES users(id),
    CHECK ((status = 'in_transit' AND resolved_at IS NULL AND resolved_by IS NULL)
        OR (status <> 'in_transit' AND resolved_at IS NOT NULL AND resolved_at >= sent_at AND resolved_by IS NOT NULL))
);
CREATE INDEX deliveries_newest_idx ON deliveries (sent_at DESC, id DESC);
CREATE INDEX deliveries_project_newest_idx ON deliveries (project_id, sent_at DESC, id DESC);
CREATE INDEX deliveries_status_newest_idx ON deliveries (status, sent_at DESC, id DESC);
CREATE INDEX deliveries_direction_newest_idx ON deliveries (direction, sent_at DESC, id DESC);
CREATE INDEX deliveries_company_in_transit_idx ON deliveries (id) WHERE direction = 'company_to_project' AND status = 'in_transit';

CREATE TABLE delivery_lines (
    delivery_id bigint NOT NULL REFERENCES deliveries(id) ON DELETE CASCADE,
    material_id bigint NOT NULL REFERENCES materials(id),
    quantity bigint NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (delivery_id, material_id)
);
CREATE INDEX delivery_lines_material_idx ON delivery_lines (material_id, delivery_id);
